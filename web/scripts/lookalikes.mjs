// Makes web/src/inbox/lookalikes.ts from Unicode's confusables data (UTS #39),
// for the owner's warning when two people who write to an inbox use names
// that look the same. Only characters that look like Latin
// letters or digits are kept, and only those that survive NFKC, which the
// page applies first.
//
//   curl -O https://www.unicode.org/Public/17.0.0/security/confusables.txt
//   node scripts/lookalikes.mjs confusables.txt
//
// The file's SHA-256 is checked, so the table is always made from the same
// data. To move to a newer version, change VERSION and SHA256 together.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const VERSION = '17.0.0'
const SHA256 = '091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a'
const OUT = new URL('../src/inbox/lookalikes.ts', import.meta.url)

const path = process.argv[2]
if (!path) {
  console.error('usage: node scripts/lookalikes.mjs confusables.txt')
  process.exit(2)
}
const raw = readFileSync(path)
const sum = createHash('sha256').update(raw).digest('hex')
if (sum !== SHA256) {
  console.error(`confusables.txt has SHA-256 ${sum}, not version ${VERSION}'s ${SHA256}`)
  process.exit(1)
}

const fromHex = (field) => String.fromCodePoint(...field.trim().split(/\s+/).map((h) => parseInt(h, 16)))
const pairs = []
for (const line of raw.toString('utf8').replace(/^\uFEFF/, '').split('\n')) {
  if (!/^[0-9A-F]/.test(line)) continue
  const [source, target] = line.split('#')[0].split(';')
  const from = fromHex(source)
  const to = fromHex(target)
  if (!/^[A-Za-z0-9]+$/.test(to)) continue // looks like something other than Latin letters or digits
  if (from.normalize('NFKC') !== from) continue // never reaches the table: NFKC comes first
  pairs.push([from, to])
}
pairs.sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0))

// Every character outside printable ASCII is written as an escape, so none
// is invisible or reorders the source.
const escape = (s) =>
  [...s]
    .map((ch) => {
      const cp = ch.codePointAt(0)
      if (cp >= 0x20 && cp < 0x7f && ch !== "'" && ch !== '\\') return ch
      return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`
    })
    .join('')

const lines = pairs.map(([from, to]) => `  ['${escape(from)}', '${to}'],`)
writeFileSync(
  OUT,
  `// Generated by web/scripts/lookalikes.mjs from Unicode's confusables.txt
// (UTS #39, version ${VERSION}, SHA-256 ${SHA256}).
// Don't edit by hand. Copyright © Unicode, Inc., under the Unicode License v3
// (see CREDITS.md).

/** Characters that look like Latin letters or digits (${pairs.length}), and the letters they look like. */
export const LOOKALIKES: ReadonlyMap<string, string> = new Map([
${lines.join('\n')}
])
`,
)
console.log(`${pairs.length} look-alikes written to ${OUT.pathname.split('/').slice(-3).join('/')}`)
